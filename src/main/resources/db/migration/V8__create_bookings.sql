CREATE TABLE bookings
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    booking_reference VARCHAR(40)              NOT NULL,
    user_id           BIGINT                   NOT NULL,
    show_id           BIGINT                   NOT NULL,

    status            VARCHAR(20)              NOT NULL,
    total_amount      NUMERIC(12, 2)           NOT NULL,

    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT uk_booking_reference
        UNIQUE (booking_reference),

    CONSTRAINT fk_booking_user
        FOREIGN KEY (user_id)
            REFERENCES users (id),

    CONSTRAINT fk_booking_show
        FOREIGN KEY (show_id)
            REFERENCES shows (id),

    CONSTRAINT chk_booking_status
        CHECK (status IN ('CONFIRMED', 'CANCELLED')),

    CONSTRAINT chk_booking_total_amount
        CHECK (total_amount >= 0)
);

CREATE INDEX idx_booking_user
    ON bookings (user_id);

CREATE INDEX idx_booking_show
    ON bookings (show_id);


CREATE TABLE booking_seats
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    booking_id BIGINT NOT NULL,
    seat_id    BIGINT NOT NULL,

    CONSTRAINT fk_booking_seat_booking
        FOREIGN KEY (booking_id)
            REFERENCES bookings (id),

    CONSTRAINT fk_booking_seat_seat
        FOREIGN KEY (seat_id)
            REFERENCES seats (id),

    CONSTRAINT uk_booking_seat
        UNIQUE (booking_id, seat_id)
);

CREATE INDEX idx_booking_seat_seat
    ON booking_seats (seat_id);
