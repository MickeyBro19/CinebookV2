CREATE TABLE show_seats
(
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    show_id BIGINT      NOT NULL,
    seat_id BIGINT      NOT NULL,

    status  VARCHAR(20) NOT NULL,

    CONSTRAINT fk_show_seat_show
        FOREIGN KEY (show_id)
            REFERENCES shows (id),

    CONSTRAINT fk_show_seat_seat
        FOREIGN KEY (seat_id)
            REFERENCES seats (id),

    CONSTRAINT uk_show_seat
        UNIQUE (show_id, seat_id),

    CONSTRAINT chk_show_seat_status
        CHECK (status IN ('AVAILABLE', 'BOOKED'))
);

CREATE INDEX idx_show_seat_show_status
    ON show_seats (show_id, status);

CREATE INDEX idx_show_seat_seat
    ON show_seats (seat_id);
