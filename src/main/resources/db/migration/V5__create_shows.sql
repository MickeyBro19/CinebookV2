CREATE TABLE shows
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    movie_id     BIGINT                   NOT NULL,
    screen_id    BIGINT                   NOT NULL,

    start_time   TIMESTAMP WITH TIME ZONE NOT NULL,
    end_time     TIMESTAMP WITH TIME ZONE NOT NULL,

    ticket_price NUMERIC(10, 2)           NOT NULL,

    status       VARCHAR(255)             NOT NULL,

    CONSTRAINT fk_show_movie
        FOREIGN KEY (movie_id)
            REFERENCES movies (id),

    CONSTRAINT fk_show_screen
        FOREIGN KEY (screen_id)
            REFERENCES screens (id),

    CONSTRAINT chk_show_time_interval
        CHECK (start_time < end_time),

    CONSTRAINT chk_show_ticket_price
        CHECK (ticket_price >= 0)
);

CREATE INDEX idx_show_screen_start
    ON shows (screen_id, start_time);

CREATE INDEX idx_show_movie
    ON shows (movie_id);
